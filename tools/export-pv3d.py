"""Pull a project from the local Solar Design Platform into the 3D page.

Writes assets/pv3d-data.js: geometry, summary and the calibrated satellite
background (inlined as a data URI), loaded by pv3d.html as a plain script so
the page also works when opened straight from disk (file://).

Usage:  python tools/export-pv3d.py [projectId] [baseUrl]
        python tools/export-pv3d.py 46707 http://localhost:8010
"""
import base64
import json
import os
import sys
import urllib.request

PID = sys.argv[1] if len(sys.argv) > 1 else '46707'
BASE = (sys.argv[2] if len(sys.argv) > 2 else 'http://localhost:8010').rstrip('/')
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'assets')


def get(path):
    with urllib.request.urlopen(BASE + path, timeout=60) as r:
        body = json.load(r)
    if not body.get('success'):
        sys.exit(f'{path}: {body.get("message")}')
    return body['data']


live = get(f'/api/projects/{PID}/live')
analysis = get(f'/api/projects/{PID}/analysis')
site = live['site']

libs = {}
buildings = []
for b in live['buildings']:
    planes = []
    for roof in b['roofs']:
        for pl in roof['planes']:
            mods = [m for m in pl['modules'] if m['visible']]
            if not mods and not pl['polygon']:
                continue
            for m in mods:
                lid = m['moduleLibraryId']
                if lid and lid not in libs:
                    libs[lid] = get(f'/api/pv-modules-library/{lid}')
            planes.append({
                'id': pl['id'],
                'poly': [[round(p['x'], 3), round(p['y'], 3), round(p['z'], 3)] for p in pl['polygon']],
                'n': [round(pl['normal'][k], 6) for k in 'xyz'],
                'pitch': pl['pitch'],
                'azimuth': pl['azimuth'],
                # per module: centre x, y (site metres), in-plan rotation (deg), library id
                'mods': [[round(m['position']['x'], 3), round(m['position']['y'], 3), m['rotation'], m['moduleLibraryId'],
                          m['dimensions']['length'], m['dimensions']['width']] for m in mods],
                'walkways': [{'w': w['width'], 'line': [[round(p['x'], 3), round(p['y'], 3)] for p in w['centerline']]}
                             for w in pl.get('walkways', []) if w.get('visible', True) and w.get('status', 'ACTIVE') == 'ACTIVE'],
            })
    buildings.append({
        'id': b['id'], 'name': b['name'], 'height': b['height'], 'base': b['baseElevation'],
        'footprint': [[round(p['x'], 3), round(p['y'], 3)] for p in b['footprint']],
        'planes': planes,
    })

bg = site.get('backgroundImage')
img = None
if bg:
    with urllib.request.urlopen(BASE + bg['url'], timeout=60) as r:
        raw = r.read()
    img = {'src': f"data:{bg.get('mime') or 'image/jpeg'};base64,{base64.b64encode(raw).decode()}", 'w': bg['width'], 'h': bg['height'], 'transform': site['calibration']['transform']}

pv, prod = analysis['pv'], analysis.get('production') or {}
data = {
    'project': {'id': live['project']['id'], 'name': live['project']['name'], 'lat': live['project']['lat'], 'lng': live['project']['lng']},
    'site': {'image': img, 'northAzimuth': site.get('northAzimuth') or 0},
    'modules': {str(k): {'name': f"{v['manufacturer']} {v['series']} {v['electrical']['power']} Wp", 'power': v['electrical']['power']} for k, v in libs.items()},
    'summary': {'moduleCount': pv['moduleCount'], 'capacityKw': pv['capacityKw'], 'annualKwh': prod.get('annualKwh'),
                'source': prod.get('source'), 'calculatedAt': analysis.get('calculatedAt')},
    'buildings': buildings,
}
with open(os.path.join(OUT, 'pv3d-data.js'), 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/export-pv3d.py from Solar Design Platform. Do not edit by hand.\n')
    f.write('window.PV3D_DATA = ' + json.dumps(data, separators=(',', ':')) + ';\n')

s = data['summary']
print(f"{live['project']['name']}: {s['moduleCount']} modules, {s['capacityKw']} kWp, "
      f"{(s['annualKwh'] or 0) / 1e6:.2f} GWh/yr, {len(buildings)} buildings, "
      f"{sum(len(p['walkways']) for b in buildings for p in b['planes'])} walkways")
